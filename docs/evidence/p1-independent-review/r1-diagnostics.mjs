import fs from 'node:fs';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
const root='/home/luishenriqs/projects/ai-orchestration-lab';
const imp=p=>import(root+'/dist/src/'+p+'.js');
const {createFixture}=await imp('execution/fixtures');
const {executeAttempt}=await imp('execution/adapter');
const {syntheticContract,syntheticApproval,syntheticReview,runScenario}=await imp('scenarios/p1');
const {trustApproval}=await imp('governance/approval');
const {canonicalHash,sha256}=await imp('contracts/integrity');
const {validationGate,prGate}=await imp('governance/gates');
const {observeTest,collectEvidence,snapshotTree}=await imp('evidence/collector');
const {createHandoff}=await imp('evidence/handoff');
const {runProcess}=await imp('execution/process');
const {sandboxArguments,probeIsolation}=await imp('execution/synthetic');
const {parseAndValidateContract}=await imp('contracts/validator');
const out=path.join(root,'docs/evidence/p1-independent-review');
const findings={};
const f=createFixture('independent-'+randomUUID(),'A');
const c=syntheticContract(f.workspace,f.base_commit,f.execution_id),ap=syntheticApproval(c);
const policy={trusted:[trustApproval(ap)],environment_authorized:true,data_classification:'SYNTHETIC_LAB',required_dependencies:[],completed_dependencies:[],conflict:false};
const o=await executeAttempt(f,c,ap,policy,'SYN-001');
findings.baseline=o.validation;
const wrong={...o.attempt,execution_id:'UNRELATED-EXECUTION',approval_id:'NONEXISTENT',executor:'codex',process_identity:{pid:1,process_start_token:'FAKE'}};
findings.forged_attempt=validationGate(f,c,wrong,o.manifest,{...o.result,execution_id:wrong.execution_id,executor:wrong.executor},o.evidence_dir,o.handoff);
const review=syntheticReview(c,o);
review.findings=[{finding_id:'HIGH-OPEN',severity:'HIGH',category:review.categories_evaluated[0].category,evidence:'Known synthetic high severity defect',source_reference:'synthetic diagnostic',recommendation:'Fix',blocking:false}];
review.verdict='APPROVED_WITH_RECOMMENDATIONS';
const merge=syntheticApproval(c,{approval_scope:'MERGE',attempt_id:'A',approved_diff_sha256:o.manifest.git.diff_sha256,review_id:review.review_id});
findings.high_nonblocking=prGate(f,c,o.attempt,o.manifest,o.result,o.handoff,review,merge,o.evidence_dir,{trusted_approvals:[trustApproval(merge)],trusted_review_sha256:[canonicalHash(review)],rollback_evaluated:true,risks_treated:true});
const raw=JSON.stringify(c).replace('"contract_revision":1','"contract_revision":666,"contract_revision":1');
const parsed=parseAndValidateContract('TaskContract',raw);
findings.duplicate_key={accepted:parsed.valid,hash_unchanged:parsed.valid&&canonicalHash(parsed.value)===canonicalHash(c)};
// Controlled fixture only: use the exact production sandbox and host observation APIs.
const evil=createFixture('independent-spoof-'+randomUUID(),'A');
const ec=syntheticContract(evil.workspace,evil.base_commit,evil.execution_id);
const dir=path.join(root,'runs',evil.execution_id);fs.mkdirSync(dir);
fs.writeFileSync(path.join(dir,'isolation-proof.json'),JSON.stringify(await probeIsolation(evil)));
const red=await observeTest(evil,dir,'red');
const payload="console.log('SYN_TEST_PASS');process.exit(0);module.exports=()=>999;";
const obs=await runProcess('/usr/bin/bwrap',sandboxArguments(evil,['src/sum.cjs'],`require('node:fs').writeFileSync('src/sum.cjs',${JSON.stringify(payload)})`),{cwd:evil.workspace});
const security=['contracts','approvals','schemas','reviews','src','dist/src'].map(p=>({path:p,digest:snapshotTree(path.join(root,p))}));
fs.writeFileSync(path.join(dir,'governance-integrity.json'),JSON.stringify({before:security,after:security,intact:true}));
fs.writeFileSync(path.join(dir,'executor-observation.json'),JSON.stringify(obs));
const a={...o.attempt,execution_id:evil.execution_id,workspace_root:evil.workspace,base_commit:evil.base_commit,approved_contract_sha256:canonicalHash(ec),started_at:obs.started_at,finished_at:new Date().toISOString(),process_identity:obs.process_identity};
const green=await observeTest(evil,dir,'green');
const m=collectEvidence(evil,ec,a,dir,red,green),h=createHandoff(ec,a,m,dir);
findings.false_green={red,green,source:payload,gate:validationGate(evil,ec,a,m,{...o.result,execution_id:evil.execution_id},dir,h),evidence_dir:dir};
fs.writeFileSync(path.join(out,'r1-diagnostics.json'),JSON.stringify(findings,null,2)+'\n');
console.log(JSON.stringify(findings,null,2));
const scenarios=path.join(out,'r1-scenarios');fs.mkdirSync(scenarios);
const results=[];for(let n=1;n<=16;n++)results.push(await runScenario(n,scenarios));
let hashes=0;for(const r of results)for(const a of r.artifacts){if(sha256(fs.readFileSync(path.join(r.evidence_directory,a.path)))!==a.sha256)throw Error('HASH_MISMATCH');hashes++;}
fs.writeFileSync(path.join(out,'r1-scenarios.json'),JSON.stringify({results,hashes_verified:hashes},null,2)+'\n');
console.log(JSON.stringify({scenarios:results.map(r=>({number:r.official_number,status:r.status})),hashes_verified:hashes}));
